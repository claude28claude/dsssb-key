"""Build data-mts.js: the separate "MTS 2026" section of the site.

Inputs (all in ./mts):
  mts-items.json   every General Awareness question of the 117 MTS 2026 shifts
                   (24 Feb - 14 May 2026), read from the answer-key compilation;
                   repeats across shifts merged, answer = the key's letter.
                   Checked: on the 16 shifts that also exist as DSSSB tick
                   prints, all 592 matching answers agree.
  mdec-*.json      one decision per id, same shape as the main bank:
                     "CA" / "X"  dropped
                     [subject, topic, explanation, example, note,
                      stem_override?, options_override?]

The answer index always comes from mts-items.json. Questions printed in Hindi
must carry an English stem and options override, or the build stops.

  python tools/build_mts.py <site folder>"""
import glob, json, os, re, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
MTS = os.path.join(HERE, 'mts')
OUT = sys.argv[1]

# Subjects, topics and text clean-up are shared with the main bank's build.py.
src = open(os.path.join(HERE, 'build.py'), encoding='utf-8').read()
shared = src[src.index('SUBJECTS = ['):src.index('rows = {')] + \
         src[src.index('def clean(s):'):src.index('# Order of questions inside a topic')] + \
         src[src.index('def english(s):'):src.index('bank = collections')]
ns = {'re': re, 'collections': collections}
exec(shared, ns)
SUBJECTS, VALID, clean, clean_option, english = ns['SUBJECTS'], ns['VALID'], ns['clean'], ns['clean_option'], ns['english']

items = {q['id']: q for q in json.load(open(os.path.join(MTS, 'mts-items.json'), encoding='utf-8'))}
dec = {}
for path in sorted(glob.glob(os.path.join(MTS, 'mdec-*.json'))):
    dec.update(json.load(open(path, encoding='utf-8')))
unknown = [i for i in dec if i not in items]
if unknown:
    raise SystemExit(f'decisions for ids not in mts-items.json: {unknown[:20]}')

MON = {'Feb': 2, 'Mar': 3, 'Apr': 4, 'May': 5}


def shift_key(label):
    # 'MTS 24 Feb 2026 S3' -> (2, 24, 3)
    _, d, m, _, s = label.split()
    return (MON[m], int(d), int(s[1]))


def hindi(s):
    return len(re.findall(r'[ऀ-ॿ]', s)) > 0


bank = collections.defaultdict(list)
counts = collections.Counter()
shifts = set()
for qid, d in dec.items():
    if isinstance(d, str):
        counts['dropped ' + d] += 1
        continue
    s, t, x, e, note = d[0], d[1], d[2], d[3], d[4]
    if s not in VALID or t not in VALID[s]:
        raise SystemExit(f'{qid}: unknown subject/topic {s}/{t}')
    r = items[qid]
    stem = english(d[5] if len(d) > 5 and d[5] else clean(r['stem']))
    opts = [english(o) for o in (d[6] if len(d) > 6 and d[6] else [clean_option(o) for o in r['o']])]
    if hindi(stem) or any(hindi(o) for o in opts):
        raise SystemExit(f'{qid}: still has Hindi text; give an English stem/options override')
    if len(opts) != 4 or not all(opts) or r['a'] not in (0, 1, 2, 3):
        raise SystemExit(f'{qid}: bad options or answer')
    srcs = sorted(r['src'], key=shift_key)
    shifts.update(srcs)
    item = {'id': qid, 'q': stem, 'o': opts, 'a': r['a'], 'x': x, 'e': e, 'src': srcs}
    if note:
        item['k'] = note
    bank[(s, t)].append(item)
    counts['kept'] += 1

os.makedirs(OUT, exist_ok=True)
subjects, total = [], 0
for sid, name, tab, blurb, topics in SUBJECTS:
    out_topics = []
    for tid, tname in topics:
        qs = sorted(bank[(sid, tid)], key=lambda q: (shift_key(q['src'][0]), q['id']))
        if qs:
            out_topics.append({'id': tid, 'n': tname, 'qs': qs})
            total += len(qs)
    if out_topics:
        subjects.append({'id': sid, 'n': name, 'tab': tab, 'w': blurb, 'topics': out_topics})
    print(f'{sid:7} {sum(len(t["qs"]) for t in out_topics):4} questions')

with open(os.path.join(OUT, 'data-mts.js'), 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/build_mts.py from the reviewed MTS 2026 answer keys. Do not edit by hand. */\n')
    f.write('window.MTS_SUBJECTS = ')
    json.dump(subjects, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')
print(dict(counts), '| written', total, '| shifts represented', len(shifts),
      '| not yet reviewed (left out):', len(items) - len(dec))
